"""Uninstallation of installed distributions, based on their ``RECORD`` metadata.

Uninstallation is split into two explicit phases:

1. :func:`plan_uninstall` inspects a ``.dist-info`` directory and builds an
   :class:`UninstallPlan`, describing exactly which files and (empty)
   directories would be removed, and which entries are kept -- together with
   the reason each one is kept.
2. :func:`apply_uninstall` executes a plan, re-checking the plan's
   preconditions as it goes, so that files replaced after planning are not
   silently deleted.

Only files with provable ownership are removed: files listed in the
distribution's own ``RECORD``, files inside the ``.dist-info`` directory
itself, and interpreter-generated bytecode (``__pycache__``) of removed
modules.  Uninstallation never scans directories to delete whatever looks
related.
"""

import os
import re
import shutil
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Union

from installer.exceptions import UninstallError
from installer.records import RecordEntry, parse_record_file

__all__ = [
    "KeptFile",
    "PlannedFile",
    "UninstallPlan",
    "UninstallResult",
    "apply_uninstall",
    "plan_uninstall",
]

_StrPath = Union[str, "os.PathLike[str]"]

#: Matches interpreter-generated bytecode file names, e.g.
#: ``module.cpython-312.pyc`` or ``module.cpython-312.opt-1.pyc``.
_PYC_PATTERN = re.compile(r"^(?P<stem>.+?)\.\w+-\d+(?:\.opt-\d)?\.pyc$")


@dataclass
class PlannedFile:
    """A file that a plan has determined is safe to remove."""

    path: Path
    """Absolute path of the file."""

    record: RecordEntry | None
    """The ``RECORD`` entry justifying the removal.

    This is ``None`` for generated files (e.g. bytecode) that are provably
    owned by the distribution without being listed in ``RECORD``.
    """

    check_content: bool = False
    """Whether the content was verified against ``record`` at plan time.

    Applying the plan re-verifies these files, to detect replacement between
    planning and applying.
    """


@dataclass
class KeptFile:
    """A path mentioned in ``RECORD`` that a plan refuses to remove."""

    path: Path
    """Absolute path of the file."""

    reason: str
    """Why the file is kept (e.g. ``"modified"``, ``"shared"``)."""


@dataclass
class UninstallPlan:
    """The result of :func:`plan_uninstall`; input to :func:`apply_uninstall`."""

    dist_info_dir: Path
    """The ``.dist-info`` directory of the distribution being uninstalled."""

    scheme_root: Path
    """Directory that ``RECORD`` paths are resolved against."""

    allowed_roots: tuple[Path, ...]
    """Canonicalized directories that removals are confined to."""

    files: list[PlannedFile] = field(default_factory=list)
    """Files to remove."""

    empty_dirs: list[Path] = field(default_factory=list)
    """Directories to remove if empty, deepest first."""

    kept: list[KeptFile] = field(default_factory=list)
    """Paths that will not be removed, with the reason for each."""


@dataclass
class UninstallResult:
    """The outcome of :func:`apply_uninstall`."""

    removed_files: list[Path]
    """Files that were removed."""

    removed_dirs: list[Path]
    """Directories that were removed (all were empty)."""

    kept: list[KeptFile]
    """Paths that were kept, carried over from the plan."""


def _canonical_roots(allowed_roots: Iterable[_StrPath]) -> tuple[Path, ...]:
    roots = tuple(Path(os.path.realpath(root)) for root in allowed_roots)
    if not roots:
        raise ValueError("at least one allowed root is required")
    return roots


def _is_within(path: Path, roots: tuple[Path, ...]) -> bool:
    return any(path == root or root in path.parents for root in roots)


def _resolve_within_roots(
    scheme_root: Path, record_path: str, roots: tuple[Path, ...]
) -> Path | None:
    """Resolve a ``RECORD`` path, or return ``None`` if it escapes the roots.

    Relative paths are resolved against ``scheme_root``.  Both ``..``
    traversal and symlinks (in any path component) are detected by comparing
    the fully resolved path against the canonicalized roots.

    The returned path is the normalized lexical path (symlinks not followed),
    so that applying the plan never deletes through a symlink.
    """
    candidate = Path(os.path.abspath(scheme_root / record_path))
    if not _is_within(Path(os.path.realpath(candidate)), roots):
        return None
    return candidate


def _read_record_entries(record_file: Path) -> list[RecordEntry]:
    with record_file.open(encoding="utf-8", newline="") as stream:
        return [RecordEntry.from_elements(*row) for row in parse_record_file(stream)]


def _paths_owned_by_others(scheme_root: Path, own_dist_info: Path) -> set[str]:
    """Collect normalized paths declared by other distributions' RECORDs."""
    owned = set()
    for record_file in sorted(scheme_root.glob("*.dist-info/RECORD")):
        if record_file.parent == own_dist_info:
            continue
        for entry in _read_record_entries(record_file):
            owned.add(os.path.abspath(scheme_root / entry.path))
    return owned


def _generated_bytecode(source: Path) -> list[Path]:
    """List bytecode files provably generated from ``source``.

    A ``.pyc`` qualifies only if it sits in the ``__pycache__`` directory
    next to ``source`` and its name matches the interpreter's cache-tag
    convention for that source's stem.
    """
    cache_dir = source.parent / "__pycache__"
    if not cache_dir.is_dir():
        return []
    return [
        child
        for child in cache_dir.iterdir()
        if child.is_file()
        and (match := _PYC_PATTERN.match(child.name)) is not None
        and match.group("stem") == source.stem
    ]


def plan_uninstall(
    dist_info: _StrPath,
    allowed_roots: Iterable[_StrPath],
    *,
    remove_modified: bool = False,
    remove_unverified: bool = False,
) -> UninstallPlan:
    """Build a plan for uninstalling the distribution at ``dist_info``.

    :param dist_info: path to the installed ``.dist-info`` directory.
    :param allowed_roots: directories that removals are confined to; any
        ``RECORD`` entry resolving outside of them (including through
        symlinks) is kept and reported.
    :param remove_modified: also remove files whose contents no longer match
        their ``RECORD`` hash/size (default: keep them).
    :param remove_unverified: also remove files outside the ``.dist-info``
        directory that have no hash and no size in ``RECORD`` (default: keep
        them, since their contents cannot be verified).
    :raises ValueError: if ``dist_info`` is not a ``.dist-info`` directory
        within one of the allowed roots.
    :raises FileNotFoundError: if there is no ``RECORD`` file.
    :raises InvalidRecordEntry: if a ``RECORD`` file cannot be parsed.
    """
    dist_info_dir = Path(dist_info)
    if not dist_info_dir.is_dir() or dist_info_dir.suffix != ".dist-info":
        raise ValueError(f"not a .dist-info directory: {dist_info_dir}")

    roots = _canonical_roots(allowed_roots)
    scheme_root = Path(os.path.abspath(dist_info_dir.parent))
    real_dist_info = Path(os.path.realpath(dist_info_dir))
    if not _is_within(real_dist_info, roots):
        raise ValueError(
            f"dist-info directory {dist_info_dir} is not within any allowed root"
        )

    record_file = dist_info_dir / "RECORD"
    if not record_file.is_file():
        raise FileNotFoundError(f"no RECORD file in {dist_info_dir}")

    dist_info_abs = Path(os.path.abspath(dist_info_dir))
    entries = _read_record_entries(record_file)
    owned_by_others = _paths_owned_by_others(scheme_root, dist_info_abs)

    plan = UninstallPlan(
        dist_info_dir=dist_info_dir,
        scheme_root=scheme_root,
        allowed_roots=roots,
    )
    dir_candidates: set[Path] = set()
    planned_paths: set[Path] = set()

    for entry in entries:
        resolved = _resolve_within_roots(scheme_root, entry.path, roots)
        if resolved is None:
            plan.kept.append(
                KeptFile(scheme_root / entry.path, "outside allowed roots")
            )
            continue

        if not os.path.lexists(resolved):
            plan.kept.append(KeptFile(resolved, "already missing"))
            continue

        if resolved.is_dir():
            # Some RECORDs list directories; only ever removed if empty.
            dir_candidates.add(resolved)
            continue

        if os.fspath(resolved) in owned_by_others:
            plan.kept.append(
                KeptFile(resolved, "also owned by another distribution")
            )
            continue

        # Files inside the .dist-info directory are provably owned by this
        # distribution, so they need no content verification.
        check_content = False
        if not (
            real_dist_info in resolved.parents or dist_info_abs in resolved.parents
        ):
            if entry.hash_ is None and entry.size is None:
                if not remove_unverified:
                    plan.kept.append(
                        KeptFile(resolved, "no hash/size to verify against")
                    )
                    continue
            elif remove_modified:
                pass
            else:
                with resolved.open("rb") as stream:
                    if not entry.validate_stream(stream):
                        plan.kept.append(
                            KeptFile(resolved, "modified after installation")
                        )
                        continue
                check_content = True

        plan.files.append(PlannedFile(resolved, entry, check_content))
        planned_paths.add(resolved)

    # Bytecode generated from removed modules is provably owned as well.
    for planned in list(plan.files):
        if planned.path.suffix != ".py":
            continue
        for pyc in _generated_bytecode(planned.path):
            if pyc not in planned_paths:
                plan.files.append(PlannedFile(pyc, None))
                planned_paths.add(pyc)

    # Directories are only removed once empty, and never the roots themselves.
    for path in planned_paths:
        parent = path.parent
        while parent != scheme_root and scheme_root in parent.parents:
            dir_candidates.add(parent)
            parent = parent.parent
    plan.empty_dirs = sorted(
        (
            d
            for d in dir_candidates
            if Path(os.path.realpath(d)) not in roots and d != scheme_root
        ),
        key=lambda d: len(d.parts),
        reverse=True,
    )
    return plan


def apply_uninstall(
    plan: UninstallPlan, *, staging_dir: _StrPath | None = None
) -> UninstallResult:
    """Execute a plan built by :func:`plan_uninstall`.

    Every planned removal is re-checked immediately before it happens: the
    path must still resolve within the plan's allowed roots, and files with a
    ``RECORD`` hash/size must still match, guarding against files being
    replaced after the plan was made.

    Uninstallation is **not** atomic.  If a pre-condition fails partway,
    :class:`UninstallError` is raised carrying the removals already performed.
    When ``staging_dir`` is given, files are first moved there (instead of
    being deleted outright) and moved back on failure; the staging directory
    is deleted once everything succeeds.  Prefer a staging directory on the
    same filesystem as the installation.

    :param plan: the plan to execute.
    :param staging_dir: optional directory to stage removals into, enabling
        best-effort restoration on failure.
    :raises UninstallError: if a pre-condition no longer holds or a removal
        fails; partial progress is available on the exception.
    """
    staging_root = Path(staging_dir) if staging_dir is not None else None
    staged: list[tuple[Path, Path]] = []
    removed: list[Path] = []

    def _restore() -> list[Path]:
        restored = []
        for original, staged_path in reversed(staged):
            try:
                original.parent.mkdir(parents=True, exist_ok=True)
                _move(staged_path, original)
            except OSError:
                continue
            restored.append(original)
        return restored

    try:
        for index, planned in enumerate(plan.files):
            path = planned.path
            if os.path.lexists(path):
                resolved = Path(os.path.realpath(path))
                if not _is_within(resolved, plan.allowed_roots):
                    raise UninstallError(
                        f"{path} no longer resolves within the allowed roots"
                    )
                if planned.check_content:
                    assert planned.record is not None
                    if not _matches_record(path, planned.record):
                        raise UninstallError(
                            f"{path} no longer matches its RECORD entry"
                        )
                if staging_root is not None:
                    staged_path = _staging_path(
                        staging_root, plan.scheme_root, path, index
                    )
                    staged_path.parent.mkdir(parents=True, exist_ok=True)
                    _move(path, staged_path)
                    staged.append((path, staged_path))
                else:
                    os.unlink(path)
            removed.append(path)
    except (OSError, UninstallError) as exc:
        restored = _restore() if staged else []
        if isinstance(exc, UninstallError):
            raise UninstallError(
                str(exc), removed=removed, restored=restored
            ) from exc
        raise UninstallError(
            f"failed to remove files: {exc}", removed=removed, restored=restored
        ) from exc

    removed_dirs = []
    for directory in plan.empty_dirs:
        resolved = Path(os.path.realpath(directory))
        if not _is_within(resolved, plan.allowed_roots):
            continue
        try:
            os.rmdir(directory)
        except OSError:
            # Not empty (e.g. contains files we must keep) or already gone.
            continue
        removed_dirs.append(directory)

    if staging_root is not None:
        shutil.rmtree(staging_root, ignore_errors=True)

    return UninstallResult(
        removed_files=removed, removed_dirs=removed_dirs, kept=plan.kept
    )


def _matches_record(path: Path, record: RecordEntry) -> bool:
    try:
        with path.open("rb") as stream:
            return record.validate_stream(stream)
    except OSError:
        return False


def _move(source: Path, dest: Path) -> None:
    """Move a file, falling back to copy-and-delete across filesystems."""
    try:
        os.replace(source, dest)
    except OSError:
        shutil.move(source, dest)


def _staging_path(
    staging_root: Path, scheme_root: Path, path: Path, index: int
) -> Path:
    try:
        relative = path.relative_to(scheme_root)
    except ValueError:
        relative = Path("_external") / f"{index}-{path.name}"
    return staging_root / relative
