"""Transactional wheel installation destination.

This module provides :any:`TransactionalSchemeDictionaryDestination`, a
:any:`~installer.destinations.WheelDestination` that prepares *all* files of
an installation in a temporary staging area before replacing anything in the
target schemes.

Cross-directory replace
-----------------------

The files of a single wheel may end up in several unrelated scheme roots
(``purelib``, ``scripts``, ``data`` ...). There is no portable way to make
such an installation atomic with a single ``rename``; even within one scheme,
the staging area is a separate directory tree. Instead this implementation
records every step in a persistent JSON journal and makes each step
individually recoverable:

- During staging, files, scripts, generated bytecode and the final ``RECORD``
  are written underneath hidden per-scheme working directories, located on the
  same filesystem as their scheme roots.
- Everything written is validated against the in-memory records, and the
  generated ``RECORD`` is re-read and checked, before any target file is
  touched.
- During commit, each target file is replaced individually. Files that
  already exist are moved aside into the working directory first, so previous
  contents can be restored.
- After an interruption,
  :any:`TransactionalSchemeDictionaryDestination.recover` either resumes the
  commit or rolls the installation back.

The journal deliberately makes no claim of cross-directory atomicity; it is an
audit trail of replacements and backups that makes the end state deterministic
after a crash.
"""

import contextlib
import json
import os
import shutil
import tempfile
import uuid
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import (
    TYPE_CHECKING,
    BinaryIO,
    Literal,
    TypedDict,
    Union,
    cast,
)

from installer.destinations import SchemeDictionaryDestination
from installer.exceptions import TransactionError
from installer.records import RecordEntry, parse_record_file
from installer.utils import (
    _WINDOWS,
    Scheme,
    _current_umask,
    construct_record_file,
)

if TYPE_CHECKING:
    from installer.scripts import LauncherKind, ScriptSection

__all__ = ["RecoveryPolicy", "TransactionalSchemeDictionaryDestination"]

RecoveryPolicy = Literal["rollback", "resume"]
"""What :any:`TransactionalSchemeDictionaryDestination.recover` should do.

- ``"rollback"`` restores the state found before the installation started.
- ``"resume"`` completes the pending commit.
"""

_JOURNAL_VERSION = 1
_JOURNAL_NAME = "transaction.json"
_WORKDIR_PREFIX = ".installer-txn-"

_Phase = Literal["staging", "prepared", "committed"]


class _WorkdirEntry(TypedDict):
    scheme: str
    path: str


class _PlanItem(TypedDict):
    scheme: str
    path: str
    kind: str
    staged: str
    target: str
    backup: str | None
    finished: bool
    previous_mode: int | None


class _Journal(TypedDict):
    version: int
    id: str
    phase: str
    scheme_dict: dict[str, str]
    interpreter: str
    script_kind: str
    hash_algorithm: str
    destdir: str | None
    bytecode_optimization_levels: list[int]
    workdirs: list[_WorkdirEntry]
    created_dirs: list[str]
    records: list[list[object]]
    root_scheme: str | None
    record_file_path: str | None
    plan: list[_PlanItem]


@dataclass
class TransactionalSchemeDictionaryDestination(SchemeDictionaryDestination):
    """Install files into a temporary staging area, then commit or roll back.

    Like :any:`SchemeDictionaryDestination`, but ``write_file``,
    ``write_script`` and ``finalize_installation`` never modify the real
    scheme roots during staging. Everything is prepared in hidden working
    directories (one per used scheme, next to its scheme root) and every
    action is recorded in a durable JSON journal under ``transaction_dir``.

    ``finalize_installation`` validates the staged tree and the generated
    ``RECORD``, then performs the non-atomic commit. If an ordinary exception
    is raised while staging or committing, the target schemes are
    automatically rolled back. If the process is killed (for example by
    :any:`KeyboardInterrupt` or :any:`SystemExit`), the journal is left behind
    and a later process can call
    :any:`TransactionalSchemeDictionaryDestination.recover`.

    Overwritten files are moved aside before their replacement is put in
    place, and directories that did not exist before the installation are only
    removed during rollback while they are empty.
    """

    transaction_dir: str | os.PathLike[str] | None = None
    """Directory holding the persistent journal.

    If ``None``, a unique directory is created in the system temporary area.
    Pass an explicit, persistent path if recovery from a *new* process must be
    possible.
    """

    # Private state (not part of the public constructor contract beyond being
    # dataclass fields).
    _staging: bool = field(default=True, init=False, repr=False, compare=False)
    _journal: _Journal | None = field(
        default=None, init=False, repr=False, compare=False
    )
    _workdirs: dict[str, Path] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )
    _journal_path: Path = field(init=False, repr=False, compare=False)
    _owns_transaction_dir: bool = field(
        default=False, init=False, repr=False, compare=False
    )

    def __post_init__(self) -> None:
        transaction_dir = self.transaction_dir
        if transaction_dir is None:
            self._owns_transaction_dir = True
            txn_path: Path = Path(tempfile.mkdtemp(prefix="installer-txn-"))
        else:
            self._owns_transaction_dir = False
            txn_path = Path(transaction_dir)
            txn_path.mkdir(parents=True, exist_ok=True)
        self.transaction_dir = str(txn_path)
        self._journal_path = txn_path / _JOURNAL_NAME

        if self._journal_path.exists():
            # Never silently clobber a journal from a previous process; the
            # caller must resolve it with ``recover`` first.
            raise TransactionError(
                f"Unfinished installation journal found at {self._journal_path}. "
                "Use TransactionalSchemeDictionaryDestination.recover() to resume "
                "or roll it back."
            )

    # ------------------------------------------------------------------
    # Path helpers
    # ------------------------------------------------------------------
    def _effective_root(self, scheme: Scheme) -> Path:
        """Real root of ``scheme`` on disk, honoring ``destdir``."""
        target_dir = Path(os.path.abspath(self.scheme_dict[scheme]))  # noqa: PTH100
        if self.destdir is not None:
            return Path(self.destdir) / target_dir.relative_to(target_dir.anchor)
        return target_dir

    def _path_with_destdir(
        self, scheme: Scheme, path: str
    ) -> Path:
        """Return either the staged or final path for ``scheme``/``path``."""
        final = super()._path_with_destdir(scheme, path)
        if self._staging:
            root = self._effective_root(scheme)
            relative = final.relative_to(root)
            workdir = self._workdir_for(scheme)
            return workdir / "staging" / relative

        return final

    def _workdir_for(self, scheme: Scheme) -> Path:
        """Get (creating on first use) the per-scheme working directory."""
        existing = self._workdirs.get(scheme)
        if existing is not None:
            return existing

        journal = self._ensure_journal()
        root = self._effective_root(scheme)

        workdir = root / f"{_WORKDIR_PREFIX}{journal['id']}"
        created: list[str] = []
        if not root.exists():
            # Track the scheme root itself for rollback cleanup, then any
            # missing parents up to the nearest existing directory.
            missing: list[Path] = []
            node = root
            while not node.exists():
                missing.append(node)
                node = node.parent
            for created_dir in reversed(missing):
                created_dir.mkdir()
                created.append(str(created_dir))

        (workdir / "staging").mkdir(parents=True)
        (workdir / "backup").mkdir()

        self._workdirs[scheme] = workdir
        journal["workdirs"].append({"scheme": scheme, "path": str(workdir)})
        journal["created_dirs"].extend(created)
        self._save_journal(journal)
        return workdir

    # ------------------------------------------------------------------
    # Journal handling
    # ------------------------------------------------------------------
    def _ensure_journal(self) -> _Journal:
        if self._journal is not None:
            return self._journal

        journal = {
            "version": _JOURNAL_VERSION,
            "id": uuid.uuid4().hex,
            "phase": "staging",
            "scheme_dict": dict(self.scheme_dict),
            "interpreter": self.interpreter,
            "script_kind": self.script_kind,
            "hash_algorithm": self.hash_algorithm,
            "destdir": self.destdir,
            "bytecode_optimization_levels": list(
                self.bytecode_optimization_levels
            ),
            "workdirs": [],
            "created_dirs": [],
            "records": [],
            "root_scheme": None,
            "record_file_path": None,
            "plan": [],
        }
        self._journal = journal
        self._save_journal(journal)
        return journal

    def _save_journal(self, journal: _Journal) -> None:
        """Atomically and durably replace the journal file."""
        path = self._journal_path
        tmp = path.with_name(f"{path.name}.tmp-{os.getpid()}")
        with tmp.open("w", encoding="utf-8") as stream:
            json.dump(journal, stream)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(tmp, path)
        directory = path.parent
        try:
            dir_fd = os.open(directory, os.O_RDONLY)  # noqa: PTH123
        except (OSError, AttributeError):  # pragma: no cover
            return
        try:
            try:
                os.fsync(dir_fd)
            except (OSError, AttributeError):  # pragma: no cover
                pass
        finally:
            os.close(dir_fd)

    # ------------------------------------------------------------------
    # Staging writes
    # ------------------------------------------------------------------
    def write_to_fs(
        self,
        scheme: Scheme,
        path: str,
        stream: BinaryIO,
        is_executable: bool,
    ) -> RecordEntry:
        """Stage a file, normalising the mode of non-executable files."""
        entry = super().write_to_fs(scheme, path, stream, is_executable)
        if not is_executable:
            target = self._path_with_destdir(scheme, path)
            target.chmod(0o666 & ~_current_umask())
        return entry

    def _record_staged(
        self, scheme: Scheme, record: RecordEntry
    ) -> None:
        journal = self._ensure_journal()
        journal["records"].append(
            [scheme, record.path, str(record.hash_ or ""), record.size]
        )
        self._save_journal(journal)

    def write_file(
        self,
        scheme: Scheme,
        path: Union[str, "os.PathLike[str]"],
        stream: BinaryIO,
        is_executable: bool,
    ) -> RecordEntry:
        """Stage a regular wheel file; see the base class for semantics."""
        record = super().write_file(scheme, path, stream, is_executable)
        self._record_staged(scheme, record)
        return record

    def write_script(
        self,
        name: str,
        module: str,
        attr: str,
        section: "ScriptSection",
    ) -> RecordEntry:
        """Stage a generated entry-point script."""
        record = super().write_script(name, module, attr, section)
        self._record_staged(Scheme("scripts"), record)
        return record

    # ------------------------------------------------------------------
    # Finalisation: validate, then commit
    # ------------------------------------------------------------------
    @contextlib.contextmanager
    def installation_context(self) -> "Iterator[None]":
        """Roll back automatically if the installation ends with an error.

        Ordinary exceptions trigger an immediate rollback. Control-flow
        interruptions such as :any:`KeyboardInterrupt` and :any:`SystemExit`
        leave the journal in place, so that another process can call
        :any:`recover` -- the process may have been killed in the middle of a
        system call, so assuming anything about on-disk state is unsafe.
        """
        try:
            yield
        except BaseException as error:
            if isinstance(error, Exception) and self._journal is not None:
                try:
                    self._rollback()
                except Exception as rollback_error:
                    raise TransactionError(
                        "Installation failed and automatic rollback failed; the "
                        f"journal at {self._journal_path} describes the remaining "
                        "state."
                    ) from rollback_error
            raise

    def finalize_installation(
        self,
        scheme: Scheme,
        record_file_path: str,
        records: Iterable[tuple[Scheme, RecordEntry]],
    ) -> None:
        """Validate the staged installation and commit it.

        Compiles bytecode into the staging area, verifies every staged file
        against its record (hashes are computed from the actual installed
        bytes, including rewritten script shebangs), writes and checks the
        ``RECORD`` file, and only then replaces target files.
        """
        record_list = list(records)
        journal = self._ensure_journal()
        journal["root_scheme"] = scheme
        journal["record_file_path"] = record_file_path

        # Bytecode is generated in staging, so the .pyc files travel through
        # the same validation/commit machinery as everything else.
        for file_scheme, record in record_list:
            self._compile_bytecode(file_scheme, record)

        extra_files = self._validate_staging(scheme, record_file_path, record_list)
        self._write_record(scheme, record_file_path, record_list)

        plan = self._build_plan(
            scheme, record_file_path, record_list, extra_files
        )
        self._preflight(plan)

        journal["phase"] = "prepared"
        journal["plan"] = plan
        self._save_journal(journal)

        self._commit()

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------
    def _prefix_for_scheme(self, root_scheme: Scheme, file_scheme: str) -> str | None:
        """Path prefix used in ``RECORD`` rows for ``file_scheme``."""
        if file_scheme == root_scheme:
            return None
        if _WINDOWS:  # pragma: no cover
            path = os.path.abspath(self.scheme_dict[file_scheme])  # noqa: PTH100
        else:  # pragma: no cover
            path = os.path.relpath(
                self.scheme_dict[file_scheme],
                start=self.scheme_dict[root_scheme],
            )
        return path + "/"

    def _validate_staging(
        self,
        root_scheme: Scheme,
        record_file_path: str,
        records: list[tuple[Scheme, RecordEntry]],
    ) -> list[tuple[Scheme, str]]:
        """Verify staged bytes against the records and find extra files.

        Extra files are expected to be generated bytecode (``.pyc`` files in
        ``__pycache__`` directories). Anything else in staging means the
        installation state is unknown and aborts the transaction.
        """
        expected: dict[tuple[str, str], RecordEntry] = {}
        for file_scheme, record in records:
            if (
                file_scheme == root_scheme
                and record.path == record_file_path
                and record.hash_ is None
            ):
                # The RECORD itself is written (and checked) afterwards.
                continue
            expected[(file_scheme, record.path)] = record

        extras: list[tuple[Scheme, str]] = []
        for file_scheme in list(self._workdirs):
            workdir = self._workdirs[file_scheme]
            staging_root = workdir / "staging"
            for staged_file in staging_root.rglob("*"):
                if not staged_file.is_file():
                    continue
                relative = staged_file.relative_to(staging_root).as_posix()
                key = (file_scheme, relative)
                record = expected.pop(key, None)
                if record is not None:
                    if record.hash_ is None:
                        continue
                    data = staged_file.read_bytes()
                    if not record.validate(data):
                        raise TransactionError(
                            f"Staged file {file_scheme}/{relative} does not match "
                            "its record (hash or size differ)."
                        )
                else:
                    parts = relative.split("/")
                    if relative.endswith(".pyc") and "__pycache__" in parts[:-1]:
                        extras.append((cast("Scheme", file_scheme), relative))
                    else:
                        raise TransactionError(
                            f"Unexpected file in staging area: "
                            f"{file_scheme}/{relative}"
                        )

        if expected:
            missing = ", ".join(f"{scheme}/{path}" for scheme, path in expected)
            raise TransactionError(f"Files missing from staging area: {missing}")

        return extras

    def _write_record(
        self,
        root_scheme: Scheme,
        record_file_path: str,
        records: list[tuple[Scheme, RecordEntry]],
    ) -> None:
        """Write the RECORD into staging and re-read it to verify contents."""
        with construct_record_file(
            records,
            lambda file_scheme: self._prefix_for_scheme(root_scheme, file_scheme),
        ) as record_stream:
            expected_bytes = record_stream.read()

        target = self._path_with_destdir(root_scheme, record_file_path)
        self._write_staged_bytes(root_scheme, record_file_path, expected_bytes)

        actual_bytes = target.read_bytes()
        if actual_bytes != expected_bytes:  # pragma: no cover - defensive
            raise TransactionError("RECORD content verification failed.")

        rows = list(parse_record_file(actual_bytes.decode("utf-8").splitlines()))
        if len(rows) != len(records):
            raise TransactionError("RECORD does not list every installed file.")
        if not any(
            row[0] == record_file_path and row[1] == "" and row[2] == ""
            for row in rows
        ):
            raise TransactionError("RECORD is missing its own entry.")

    def _write_staged_bytes(
        self, scheme: Scheme, path: str, contents: bytes
    ) -> None:
        """Write ``contents`` to ``path`` in the staging area.

        A separate method so failures while materialising the final ``RECORD``
        can be simulated at the same boundary as real disk errors.
        """
        target = self._path_with_destdir(scheme, path)
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("wb") as stream:
            stream.write(contents)
        target.chmod(0o666 & ~_current_umask())

    # ------------------------------------------------------------------
    # Plan + commit
    # ------------------------------------------------------------------
    def _build_plan(
        self,
        root_scheme: Scheme,
        record_file_path: str,
        records: list[tuple[Scheme, RecordEntry]],
        extras: list[tuple[Scheme, str]],
    ) -> list[_PlanItem]:
        """Describe every file movement required to finish the install.

        Regular files and scripts come first; generated bytecode follows; the
        ``RECORD`` is placed last, so an interrupted commit never leaves a new
        RECORD describing files that are not yet in place.
        """
        plan: list[_PlanItem] = []

        def add(file_scheme: Scheme, relative: str, kind: str) -> None:
            staged = self._path_with_destdir(file_scheme, relative)
            target = self._effective_root(file_scheme) / relative
            plan.append(
                {
                    "scheme": file_scheme,
                    "path": relative,
                    "kind": kind,
                    "staged": str(staged),
                    "target": str(target),
                    "backup": None,
                    "finished": False,
                    "previous_mode": None,
                }
            )

        for file_scheme, record in records:
            if (
                file_scheme == root_scheme
                and record.path == record_file_path
                and record.hash_ is None
            ):
                continue
            add(file_scheme, record.path, "file")

        for file_scheme, relative in extras:
            add(file_scheme, relative, "bytecode")

        # RECORD is staged on disk at this point, so its staging path resolves
        # correctly and the target overwrites the previous installation's
        # RECORD last.
        add(root_scheme, record_file_path, "record")
        return plan

    def _preflight(self, plan: list[_PlanItem]) -> None:
        """Refuse to clobber existing targets when overwriting is disabled."""
        if self.overwrite_existing:
            return
        for item in plan:
            target = item["target"]
            if os.path.lexists(target):
                raise FileExistsError(f"File already exists: {target}")

    def _ensure_commit_parent(self, item: _PlanItem) -> None:
        """Create missing target parent directories, recording ownership."""
        target = Path(item["target"])
        root = self._effective_root(cast("Scheme", item["scheme"]))
        missing: list[Path] = []
        node = target.parent
        while not node.exists():
            missing.append(node)
            node = node.parent
            if node != root and root not in node.parents:  # pragma: no cover
                raise TransactionError(
                    f"Refusing to create {target.parent} outside of {root}"
                )
        created: list[str] = []
        for directory in reversed(missing):
            directory.mkdir()
            created.append(str(directory))
        if created:
            journal = self._journal
            assert journal is not None
            journal["created_dirs"].extend(created)
            self._save_journal(journal)

    def _replace_file(self, source: str | os.PathLike[str], destination: str) -> None:
        """Move ``source`` onto ``destination``.

        This is a separate method so tests can inject failures at the exact
        replacement boundary.
        """
        os.replace(source, destination)
        parent = Path(destination).parent
        try:  # pragma: no cover - best-effort durability
            dir_fd = os.open(parent, os.O_RDONLY)  # noqa: PTH123
        except (OSError, AttributeError):
            return
        try:  # pragma: no cover
            os.fsync(dir_fd)
        except (OSError, AttributeError):  # pragma: no cover
            pass
        finally:  # pragma: no cover
            os.close(dir_fd)

    def _commit(self) -> None:
        """Replace target files one by one, per the journaled plan."""
        journal = self._journal
        assert journal is not None
        plan = journal["plan"]

        self._staging = False
        for index, item in enumerate(plan):
            if item["finished"]:
                continue

            target = item["target"]
            staged = item["staged"]
            self._ensure_commit_parent(item)

            if item["backup"] is None and os.path.lexists(target):
                workdir = self._workdirs[cast("Scheme", item["scheme"])]
                backup = (
                    workdir
                    / "backup"
                    / f"{index:06d}-{Path(target).name}"
                )
                previous_mode = os.stat(target).st_mode
                self._replace_file(target, str(backup))
                item["backup"] = str(backup)
                item["previous_mode"] = previous_mode
                self._save_journal(journal)

            self._replace_file(staged, target)
            previous_mode = item.get("previous_mode")
            if previous_mode is not None:
                # Keep the predecessor's permission bits when upgrading, so
                # e.g. an executable data file stays executable.
                os.chmod(target, int(previous_mode))
            item["finished"] = True
            self._save_journal(journal)

        journal["phase"] = "committed"
        self._save_journal(journal)
        self._cleanup_success()

    def _cleanup_success(self) -> None:
        """Remove working directories and the journal after a full commit."""
        journal = self._journal
        assert journal is not None
        for entry in journal["workdirs"]:
            shutil.rmtree(entry["path"], ignore_errors=True)
        try:
            self._journal_path.unlink()
        except FileNotFoundError:
            pass
        try:
            self._journal_path.parent.rmdir()
        except OSError:
            pass

    # ------------------------------------------------------------------
    # Rollback
    # ------------------------------------------------------------------
    def _rollback(self) -> None:
        """Restore targets from backups, then remove our files and dirs."""
        journal = self._journal
        if journal is None:
            raise TransactionError("No transaction journal to roll back.")

        plan = journal["plan"]
        self._staging = False

        for item in reversed(plan):
            target = item["target"]
            backup = item["backup"]
            already_restored = not item["finished"] and backup is None

            if not already_restored and backup is not None and os.path.lexists(
                backup
            ):
                # An old file was moved aside; remove whatever is at the
                # target and put the old bytes back.
                if os.path.lexists(target):
                    os.unlink(target)
                self._replace_file(backup, target)
            elif not already_restored and backup is None and item["finished"]:
                # A brand-new file with no predecessor.
                if os.path.lexists(target):
                    os.unlink(target)
            # If already_restored is true, this item was handled by an earlier
            # rollback pass; the backup is gone and the target reflects the
            # pre-installation state.

            item["finished"] = False
            item["backup"] = None
            self._save_journal(journal)

        # Remove directories this installation created. Only empty,
        # installation-owned directories are eligible.
        for directory in sorted(
            journal["created_dirs"],
            key=lambda value: len(Path(value).parts),
            reverse=True,
        ):
            try:
                os.rmdir(directory)
            except OSError:
                pass

        for entry in journal["workdirs"]:
            shutil.rmtree(entry["path"], ignore_errors=True)

        journal["phase"] = "rolled_back"
        self._save_journal(journal)

        try:
            self._journal_path.unlink()
        except FileNotFoundError:
            pass
        try:
            self._journal_path.parent.rmdir()
        except OSError:
            pass

    # ------------------------------------------------------------------
    # Recovery from another process
    # ------------------------------------------------------------------
    @classmethod
    def recover(
        cls,
        transaction_dir: Union[str, "os.PathLike[str]"],
        policy: RecoveryPolicy = "resume",
    ) -> "TransactionalSchemeDictionaryDestination":
        """Resume or roll back a transaction left behind by a dead process.

        :param transaction_dir: directory given (or created automatically) when
            the original destination was constructed.
        :param policy: ``"resume"`` completes the commit; ``"rollback"``
            restores the pre-installation state.
        """
        journal_path = Path(transaction_dir) / _JOURNAL_NAME
        try:
            with journal_path.open("r", encoding="utf-8") as stream:
                journal: _Journal = json.load(stream)
        except FileNotFoundError as error:
            raise TransactionError(
                f"No transaction journal found at {journal_path}"
            ) from error
        except (OSError, json.JSONDecodeError) as error:
            raise TransactionError(
                f"Transaction journal at {journal_path} is unreadable"
            ) from error

        if journal.get("version") != _JOURNAL_VERSION:
            raise TransactionError(
                f"Unsupported transaction journal version in {journal_path}"
            )

        phase = cast("_Phase", journal.get("phase"))
        if policy == "resume" and phase in ("staging", "rolled_back"):
            raise TransactionError(
                f"Can not resume a transaction in the {phase!r} phase; "
                "use policy='rollback' instead."
            )

        # Construct through the normal initializer with a throwaway directory,
        # then re-attach to the persisted transaction.
        instance = cls(
            scheme_dict=dict(journal["scheme_dict"]),
            interpreter=journal["interpreter"],
            script_kind=cast("LauncherKind", journal["script_kind"]),
            hash_algorithm=journal["hash_algorithm"],
            bytecode_optimization_levels=tuple(
                journal["bytecode_optimization_levels"]
            ),
            destdir=journal["destdir"],
            transaction_dir=None,
        )
        if instance._owns_transaction_dir:
            shutil.rmtree(instance.transaction_dir, ignore_errors=True)
        instance.transaction_dir = os.fspath(transaction_dir)
        instance._journal_path = journal_path
        instance._journal = journal
        instance._workdirs = {
            cast("Scheme", entry["scheme"]): Path(entry["path"])
            for entry in journal["workdirs"]
        }

        if policy == "rollback":
            instance._rollback()
        else:
            instance._commit()
        return instance
