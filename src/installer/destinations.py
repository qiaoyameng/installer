"""Handles all file writing and post-installation processing."""

import importlib.util
import io
import os
from collections.abc import Collection, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, BinaryIO, Union

from installer.exceptions import ReproducibleInstallError
from installer.records import Hash, RecordEntry
from installer.scripts import Script
from installer.utils import (
    _WINDOWS,
    Scheme,
    construct_record_file,
    copyfileobj_with_hashing,
    fix_shebang,
    get_source_date_epoch,
    make_file_executable,
)

if TYPE_CHECKING:
    from installer.scripts import LauncherKind, ScriptSection


class WheelDestination:
    """Handles writing the unpacked files, script generation and ``RECORD`` generation.

    Subclasses provide the concrete script generation logic, as well as the RECORD file
    (re)writing.
    """

    def write_script(
        self, name: str, module: str, attr: str, section: "ScriptSection"
    ) -> RecordEntry:
        """Write a script in the correct location to invoke given entry point.

        :param name: name of the script
        :param module: module path, to load the entry point from
        :param attr: final attribute access, for the entry point
        :param section: Denotes the "entry point section" where this was specified.
            Valid values are ``"gui"`` and ``"console"``.
        :type section: str

        Example usage/behaviour::

            >>> dest.write_script("pip", "pip._internal.cli", "main", "console")

        """
        raise NotImplementedError

    def write_file(
        self,
        scheme: Scheme,
        path: Union[str, "os.PathLike[str]"],
        stream: BinaryIO,
        is_executable: bool,
    ) -> RecordEntry:
        """Write a file to correct ``path`` within the ``scheme``.

        :param scheme: scheme to write the file in (like "purelib", "platlib" etc).
        :param path: path within that scheme
        :param stream: contents of the file
        :param is_executable: whether the file should be made executable

        The stream would be closed by the caller, after this call.

        Example usage/behaviour::

            >>> with open("__init__.py") as stream:
            ...     dest.write_file("purelib", "pkg/__init__.py", stream)

        """
        raise NotImplementedError

    def finalize_installation(
        self,
        scheme: Scheme,
        record_file_path: str,
        records: Iterable[tuple[Scheme, RecordEntry]],
    ) -> None:
        """Finalize installation, after all the files are written.

        Handles (re)writing of the ``RECORD`` file.

        :param scheme: scheme to write the ``RECORD`` file in
        :param record_file_path: path of the ``RECORD`` file with that scheme
        :param records: entries to write to the ``RECORD`` file

        Example usage/behaviour::

            >>> dest.finalize_installation("purelib")

        """
        raise NotImplementedError


@dataclass
class SchemeDictionaryDestination(WheelDestination):
    """Destination, based on a mapping of {scheme: file-system-path}."""

    scheme_dict: dict[str, str]
    """A mapping of {scheme: file-system-path}"""

    interpreter: str
    """The interpreter to use for generating scripts."""

    script_kind: "LauncherKind"
    """The "kind" of launcher script to use."""

    hash_algorithm: str = "sha256"
    """
    The hashing algorithm to use, which is a member of
    :any:`hashlib.algorithms_available` (ideally from
    :any:`hashlib.algorithms_guaranteed`).
    """

    bytecode_optimization_levels: Collection[int] = ()
    """
    Compile cached bytecode for installed .py files with these optimization
    levels. The bytecode is specific to the minor version of Python (e.g. 3.10)
    used to generate it.
    """

    destdir: str | None = None
    """
    A staging directory in which to write all files. This is expected to be the
    filesystem root at runtime, so embedded paths will be written as though
    this was the root.
    """

    overwrite_existing: bool = False
    """Silently overwrite existing files."""

    reproducible: bool = False
    """
    Perform a reproducible installation.

    When enabled, all written artifacts are made byte-for-byte reproducible:

    - Files get fixed permissions (``0o755`` for executable files and
      scripts, ``0o644`` for regular files) and a fixed modification time
      taken from :attr:`source_date_epoch`. Directories created during the
      installation get ``0o755`` permissions and the same modification time.
    - ``RECORD`` is written in a deterministic order.
    - Generated bytecode uses explicit hash-based invalidation
      (:pep:`552` ``CHECKED_HASH``), with the code's ``co_filename`` set to
      the logical installation path (never the staging directory).

    Reproducibility is guaranteed across different :attr:`destdir` staging
    directories, as long as the logical ``scheme_dict`` paths, the
    interpreter, the wheel contents and the Python bytecode version match.
    Byte-identical output across different Python versions is not promised.
    """

    source_date_epoch: int | None = None
    """
    Fixed modification time (seconds since the Unix epoch) used for
    reproducible installations.

    When :attr:`reproducible` is enabled and this is ``None``, the value is
    read from the ``SOURCE_DATE_EPOCH`` environment variable. An unset or
    invalid value raises
    :class:`installer.exceptions.ReproducibleInstallError` -- installation
    never silently falls back to non-reproducible behavior.
    """

    _written_directories: set[Path] = field(init=False, default_factory=set)
    _target_interpreter_checked: bool = field(init=False, default=False)

    def __post_init__(self) -> None:
        """Validate reproducible-installation prerequisites."""
        if not self.reproducible:
            return

        if self.source_date_epoch is None:
            self.source_date_epoch = get_source_date_epoch()
        elif not isinstance(self.source_date_epoch, int) or isinstance(
            self.source_date_epoch, bool
        ):
            raise ReproducibleInstallError(
                "source_date_epoch must be a non-negative integer (seconds "
                f"since the Unix epoch), got {self.source_date_epoch!r}."
            )

        if self.source_date_epoch < 0:
            raise ReproducibleInstallError(
                "source_date_epoch must be a non-negative integer, got "
                f"{self.source_date_epoch}."
            )

    def _path_with_destdir(self, scheme: Scheme, path: str) -> Path:
        # See https://docs.python.org/3/library/zipfile.html#zipfile.Path:
        #  When handling untrusted archives,
        #  consider resolving filenames using os.path.abspath()
        #  and checking against the target directory with os.path.commonpath().
        #
        # Attention: Path.absolute() is not sufficient because it does not
        #  normalize, i.e. does not remove "..".
        #
        # We want to avoid Path.resolve() because it is significantly slower
        # than os.path.abspath()!
        target_dir = Path(os.path.abspath(self.scheme_dict[scheme]))  # noqa: PTH100
        file = Path(os.path.abspath(target_dir / path))  # noqa: PTH100

        if not file.is_relative_to(target_dir):
            raise ValueError(
                f"Attempting to write {path} outside of the target directory"
            )

        if self.destdir is not None:
            rel_path = file.relative_to(file.anchor)
            return Path(self.destdir) / rel_path
        return file

    def write_to_fs(
        self,
        scheme: Scheme,
        path: str,
        stream: BinaryIO,
        is_executable: bool,
    ) -> RecordEntry:
        """Write contents of ``stream`` to the correct location on the filesystem.

        :param scheme: scheme to write the file in (like "purelib", "platlib" etc).
        :param path: path within that scheme
        :param stream: contents of the file
        :param is_executable: whether the file should be made executable

        - Ensures that an existing file is not being overwritten.
        - Hashes the written content, to determine the entry in the ``RECORD`` file.
        """
        target_path = self._path_with_destdir(scheme, path)
        if not self.overwrite_existing and target_path.exists():
            message = f"File already exists: {target_path!s}"
            raise FileExistsError(message)

        parent_folder = target_path.parent
        if not parent_folder.exists():
            parent_folder.mkdir(parents=True)
        if self.reproducible:
            self._track_installation_directories(scheme, target_path)

        with target_path.open("wb") as f:
            hash_, size = copyfileobj_with_hashing(stream, f, self.hash_algorithm)

        if self.reproducible:
            # Fixed permissions: executable files/scripts are 0o755,
            # everything else is 0o644.
            target_path.chmod(0o755 if is_executable else 0o644)
            os.utime(target_path, (self.source_date_epoch, self.source_date_epoch))
        elif is_executable:
            make_file_executable(target_path)

        return RecordEntry(path, Hash(self.hash_algorithm, hash_), size)

    def _track_installation_directories(
        self, scheme: Scheme, target_path: Path
    ) -> None:
        """Record every directory from the install root to ``target_path``.

        Reproducible installs normalize the metadata of every directory they
        touch, including ones created implicitly by ``mkdir(parents=True)``.
        """
        root = Path(os.path.abspath(self.scheme_dict[scheme]))  # noqa: PTH100
        if self.destdir is not None:
            root = Path(os.path.abspath(self.destdir))  # noqa: PTH100

        directory = Path(
            os.path.abspath(target_path.parent)
        )  # noqa: PTH100
        while True:
            self._written_directories.add(directory)
            if directory == root or not directory.is_relative_to(root):
                break
            directory = directory.parent

    def write_file(
        self,
        scheme: Scheme,
        path: Union[str, "os.PathLike[str]"],
        stream: BinaryIO,
        is_executable: bool,
    ) -> RecordEntry:
        """Write a file to correct ``path`` within the ``scheme``.

        :param scheme: scheme to write the file in (like "purelib", "platlib" etc).
        :param path: path within that scheme
        :param stream: contents of the file
        :param is_executable: whether the file should be made executable

        - Changes the shebang for files in the "scripts" scheme.
        - Uses :py:meth:`SchemeDictionaryDestination.write_to_fs` for the
          filesystem interaction.
        """
        path_ = os.fspath(path)

        if scheme == "scripts":
            with fix_shebang(stream, self.interpreter) as stream_with_different_shebang:
                return self.write_to_fs(
                    scheme, path_, stream_with_different_shebang, is_executable
                )

        return self.write_to_fs(scheme, path_, stream, is_executable)

    def write_script(
        self, name: str, module: str, attr: str, section: "ScriptSection"
    ) -> RecordEntry:
        """Write a script to invoke an entrypoint.

        :param name: name of the script
        :param module: module path, to load the entry point from
        :param attr: final attribute access, for the entry point
        :param section: Denotes the "entry point section" where this was specified.
            Valid values are ``"gui"`` and ``"console"``.
        :type section: str

        - Generates a launcher using :any:`Script.generate`.
        - Writes to the "scripts" scheme.
        - Uses :py:meth:`SchemeDictionaryDestination.write_to_fs` for the
          filesystem interaction.
        """
        script = Script(name, module, attr, section)
        script_name, data = script.generate(self.interpreter, self.script_kind)

        with io.BytesIO(data) as stream:
            entry = self.write_to_fs(
                Scheme("scripts"), script_name, stream, is_executable=True
            )

            if not self.reproducible:
                path = self._path_with_destdir(Scheme("scripts"), script_name)
                mode = path.stat().st_mode
                mode |= (mode & 0o444) >> 2
                path.chmod(mode)

            return entry

    def _compile_bytecode(self, scheme: Scheme, record: RecordEntry) -> None:
        """Compile bytecode for a single .py file."""
        if not self.bytecode_optimization_levels or scheme not in (
            "purelib",
            "platlib",
        ):
            return

        import compileall

        target_path = self._path_with_destdir(scheme, record.path)
        dir_path_to_embed = (Path(self.scheme_dict[scheme]) / record.path).parent

        for level in self.bytecode_optimization_levels:
            compileall.compile_file(
                target_path, optimize=level, quiet=1, ddir=dir_path_to_embed
            )

    def _ensure_interpreter_supports_hash_pyc(self) -> None:
        """Verify the target interpreter can generate hash-based bytecode.

        Reproducible installs require :pep:`552` hash-based bytecode
        invalidation, which needs Python 3.7 or newer. The generated bytecode
        is also only usable by an interpreter with a matching bytecode magic
        number, so verify the configured target interpreter (not necessarily
        the running one, especially when staging via ``destdir``).

        :raises ReproducibleInstallError: if the interpreter cannot be run, is
            older than 3.7, or has a different bytecode magic number.
        """
        import subprocess

        if self._target_interpreter_checked:
            return

        probe = (
            "import sys, importlib.util;"
            "print('%d.%d.%d' % sys.version_info[:3]);"
            "print(importlib.util.MAGIC_NUMBER.hex())"
        )
        try:
            result = subprocess.run(
                [self.interpreter, "-c", probe],
                check=True,
                capture_output=True,
                text=True,
            )
        except (OSError, subprocess.CalledProcessError) as exc:
            raise ReproducibleInstallError(
                "Cannot verify that the target interpreter supports hash-based "
                f"bytecode: could not run {self.interpreter!r}: {exc}"
            ) from exc

        lines = result.stdout.split()
        try:
            version_parts: list[int] = [
                int(part) for part in lines[0].split(".")
            ]
            magic_hex = lines[1]
        except (IndexError, ValueError) as exc:
            raise ReproducibleInstallError(
                "Unexpected output while probing the target interpreter "
                f"{self.interpreter!r}: {result.stdout!r}"
            ) from exc

        version_tuple: tuple[int, ...] = tuple(version_parts[:2])
        if version_tuple < (3, 7):
            raise ReproducibleInstallError(
                f"The target interpreter {self.interpreter!r} is Python "
                f"{lines[0]}, which does not support hash-based bytecode "
                "invalidation (PEP 552 requires Python 3.7 or newer). "
                "Refusing to fall back to timestamp-based bytecode, since the "
                "installation would not be reproducible."
            )

        if magic_hex != importlib.util.MAGIC_NUMBER.hex():
            raise ReproducibleInstallError(
                f"The target interpreter {self.interpreter!r} (Python "
                f"{lines[0]}) has a different bytecode magic number "
                f"({magic_hex}) than the running interpreter "
                f"({importlib.util.MAGIC_NUMBER.hex()}). Hash-based bytecode "
                "could still be generated, but it would not be usable by the "
                "target interpreter and byte-identical output across Python "
                "versions is not promised."
            )

        self._target_interpreter_checked = True

    def _compile_reproducible_bytecode(
        self, scheme: Scheme, record: RecordEntry
    ) -> None:
        """Compile hash-based, timestamp-independent bytecode for a .py file."""
        import py_compile

        if (
            not self.bytecode_optimization_levels
            or scheme not in ("purelib", "platlib")
            or not record.path.endswith(".py")
        ):
            return

        self._ensure_interpreter_supports_hash_pyc()

        # The source lives under the staging directory, while ``dfile`` embeds
        # the logical installation path -- never the random staging path.
        staged_path = self._path_with_destdir(scheme, record.path)
        logical_path = Path(self.scheme_dict[scheme]) / record.path

        for level in self.bytecode_optimization_levels:
            pyc_name = Path(
                importlib.util.cache_from_source(
                    record.path, optimization=level if level >= 1 else ""
                )
            ).name
            pyc_path = staged_path.parent / pyc_name
            self._written_directories.add(
                Path(os.path.abspath(pyc_path.parent))  # noqa: PTH100
            )
            py_compile.compile(
                str(staged_path),
                cfile=str(pyc_path),
                dfile=str(logical_path),
                doraise=True,
                optimize=level,
                invalidation_mode=py_compile.PycInvalidationMode.CHECKED_HASH,
                quiet=1,
            )

            pyc_path.chmod(0o644)
            os.utime(pyc_path, (self.source_date_epoch, self.source_date_epoch))

    def finalize_installation(
        self,
        scheme: Scheme,
        record_file_path: str,
        records: Iterable[tuple[Scheme, RecordEntry]],
    ) -> None:
        """Finalize installation, by writing the ``RECORD`` file & compiling bytecode.

        :param scheme: scheme to write the ``RECORD`` file in
        :param record_file_path: path of the ``RECORD`` file with that scheme
        :param records: entries to write to the ``RECORD`` file
        """

        def prefix_for_scheme(file_scheme: str) -> str | None:
            if file_scheme == scheme:
                return None
            if _WINDOWS:  # pragma: no cover
                path = os.path.abspath(self.scheme_dict[file_scheme])  # noqa: PTH100
            else:  # pragma: no cover
                path = os.path.relpath(
                    self.scheme_dict[file_scheme],
                    start=self.scheme_dict[scheme],
                )
            return path + "/"

        record_list = list(records)
        with construct_record_file(record_list, prefix_for_scheme) as record_stream:
            self.write_to_fs(
                scheme, record_file_path, record_stream, is_executable=False
            )

        for scheme_, record in record_list:
            if self.reproducible:
                self._compile_reproducible_bytecode(scheme_, record)
            else:
                self._compile_bytecode(scheme_, record)

        if self.reproducible:
            self._finalize_directory_metadata()

    def _finalize_directory_metadata(self) -> None:
        """Give every created directory fixed permissions and mtime.

        Directories are processed deepest-first, so changing a child's
        metadata cannot bump a parent directory's modification time after it
        has been normalized.
        """
        for directory in sorted(
            self._written_directories,
            key=lambda path: len(path.parts),
            reverse=True,
        ):
            if directory.exists():
                directory.chmod(0o755)
                os.utime(
                    directory,
                    (self.source_date_epoch, self.source_date_epoch),
                )
